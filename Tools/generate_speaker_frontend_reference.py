"""Regenerate synthetic (no personal audio) SpeechBrain frontend reference values.

Run from repository root: python3 Tools/generate_speaker_frontend_reference.py
NumPy rfft is independent of the Swift 400-point matrix DFT implementation.
Conventions verified from primary sources:
https://huggingface.co/speechbrain/spkrec-ecapa-voxceleb/blob/main/hyperparams.yaml
https://github.com/speechbrain/speechbrain/blob/v1.0.3/speechbrain/lobes/features.py
https://github.com/speechbrain/speechbrain/blob/v1.0.3/speechbrain/processing/features.py

Fbank defaults: 400-point STFT, 25ms periodic Hamming, 10ms hop, constant
center padding, power spectrum, symmetric Hz triangles, 10log10, top_db=80.
ECAPA config: sentence mean normalization, std_norm=False.
"""
from pathlib import Path
import numpy as np

n = np.arange(48000)
t = n / 16000.0
noise = ((n * 1103515245 + 12345) % 65536) / 65535.0 - 0.5
envelope = 0.45 + 0.35 * np.sin(4 * np.pi * t)
signal = (0.15 * envelope * np.sin(2 * np.pi * (115 * t + 45 * t**2))
          + 0.04 * np.cos(2 * np.pi * 1700 * t) + 0.015 * noise).astype(np.float32)
window = (0.54 - 0.46 * np.cos(2 * np.pi * np.arange(400) / 400)).astype(np.float32)
padded = np.pad(signal, (200, 200))
frames = np.lib.stride_tricks.sliding_window_view(padded, 400)[::160] * window
spectrum = np.abs(np.fft.rfft(frames, n=400)) ** 2
points = 700 * (10 ** (np.linspace(0, 2595 * np.log10(1 + 8000 / 700), 82) / 2595) - 1)
centers = points[1:-1]
band = np.diff(points)[:-1]
filters = np.maximum(0, 1 - np.abs(np.arange(201)[:, None] * 40 - centers) / band)
db = 10 * np.log10(np.maximum(spectrum @ filters, 1e-10))
db = np.maximum(db, db.max() - 80)
features = db - db.mean(axis=0, keepdims=True)
frames_to_check = [0, 1, 19, 71, 150, 231, 299, 300]
bands_to_check = [0, 3, 10, 22, 39, 51, 67, 79]
checks = [(frame * 80 + band, features[frame, band]) for frame in frames_to_check for band in bands_to_check]
text = '''// Generated by Tools/generate_speaker_frontend_reference.py; synthetic waveform only.
// NumPy rfft oracle using the official SpeechBrain Fbank + ECAPA normalization conventions.
enum SpeakerFrontendReference {
    static let samples: [(Int, Float)] = [
'''
text += ''.join(f'        ({index}, {value:.8f}),\n' for index, value in checks)
text += f'    ]\n    static let rms: Double = {np.sqrt(np.mean(features ** 2)):.10f}\n}}\n'
Path('Tests/GravityReaderTests/SpeakerFrontendReference.swift').write_text(text)
